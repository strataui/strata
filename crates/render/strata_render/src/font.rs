/// Retrieves the 8x16 bitmask slice for a given printable ASCII character.
#[inline]
pub fn get_glyph(c: char) -> Option<&'static [u8; 16]> {
    let code = c as u32;
    if (32..=126).contains(&code) {
        Some(&FONT_8X16[(code - 32) as usize])
    } else {
        None
    }
}

